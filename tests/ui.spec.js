import {test,expect} from '@playwright/test';
test('Create, read, search, edit, cancel and confirm deletion; mobile layout',async({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');await expect(page.getByText('SQLite connected')).toBeVisible();
  await page.getByLabel('Product name',{exact:true}).fill('React Lab Demo');
  await page.getByLabel('Vendor / maintainer').fill('Meta');
  await page.getByLabel('Installed version').fill('19.2.0');
  await page.getByLabel('Staging',{exact:true}).check();
  await page.getByLabel('Review priority').selectOption('High');
  await page.getByLabel('Notes',{exact:true}).fill('Demonstration record; not live threat data.');
  await page.screenshot({path:'docs/screenshots/01-create-form.png',fullPage:true});
  await page.getByRole('button',{name:'Add software'}).click();
  await expect(page.getByRole('status')).toContainText('added successfully');
  await page.screenshot({path:'docs/screenshots/02-read.png',fullPage:true});
  await page.reload();await expect(page.getByRole('heading',{name:'React Lab Demo'})).toBeVisible();
  await page.getByRole('textbox',{name:'Search software'}).fill('no-match');
  await expect(page.getByText('No matching software')).toBeVisible();
  await page.getByRole('textbox',{name:'Search software'}).fill('React');
  await page.screenshot({path:'docs/screenshots/03-search.png',fullPage:true});
  await page.getByRole('button',{name:'Edit React Lab Demo',exact:true}).click();
  await page.getByLabel('Installed version').fill('20.0.0');
  await page.getByRole('button',{name:'Save changes'}).click();
  await expect(page.getByText('v20.0.0',{exact:true})).toBeVisible();
  await page.screenshot({path:'docs/screenshots/04-update.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'docs/screenshots/05-mobile.png',fullPage:true});
  await page.setViewportSize({width:1280,height:900});
  await page.getByRole('button',{name:'Delete React Lab Demo',exact:true}).click();
  await page.getByRole('button',{name:'Keep record'}).click();
  await expect(page.getByRole('heading',{name:'React Lab Demo'})).toBeVisible();
  await page.getByRole('button',{name:'Delete React Lab Demo',exact:true}).click();
  await page.screenshot({path:'docs/screenshots/06-delete-confirmation.png',fullPage:true});
  await page.getByRole('button',{name:'Delete record',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('deleted successfully');
  await page.screenshot({path:'docs/screenshots/07-delete-result.png',fullPage:true});
  expect(errors).toEqual([]);
});
